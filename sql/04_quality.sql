-- Reconcile every headline number that is quoted in the report.
SELECT
  (SELECT count(*) FROM sessions) AS requests,
  (SELECT count(DISTINCT session_id) FROM sessions) AS distinct_sessions,
  (SELECT count(*) FROM exposures) AS exposure_rows,
  (SELECT sum(impressions) FROM sessions) AS request_exposures,
  (SELECT sum(is_clicked) FROM exposures) AS exposure_clicks,
  (SELECT sum(clicks) FROM sessions) AS request_clicks,
  (SELECT sum(is_purchased) FROM exposures) AS exposure_purchases,
  (SELECT sum(purchases) FROM sessions) AS request_purchases,
  (SELECT count(*) FROM items) AS item_rows,
  (SELECT count(DISTINCT item_id) FROM items) AS distinct_items,
  (SELECT count(*) FROM users) AS user_rows,
  (SELECT count(DISTINCT user_id) FROM users) AS distinct_users,
  (SELECT count(*) FROM exposures AS e LEFT JOIN items AS i USING (item_id) WHERE i.item_id IS NULL) AS missing_item_exposures,
  (SELECT count(*) FROM sessions AS s LEFT JOIN users AS u USING (user_id) WHERE u.user_id IS NULL) AS missing_user_requests,
  (SELECT count(*) FROM exposures AS e JOIN sessions AS s USING (session_id) WHERE e.position < 1 OR e.position > s.impressions) AS bad_positions,
  (SELECT min(position) FROM exposures) AS min_position,
  (SELECT max(position) FROM exposures) AS max_position,
  (SELECT count(DISTINCT length_stratum) FROM sessions) AS distinct_length_strata,
  (SELECT count(*) FROM sessions AS s LEFT JOIN query_intent AS qi USING (query) WHERE qi.intent IS NULL) AS unclassified_requests,
  (SELECT count(DISTINCT query) FROM query_intent) AS tagged_query_rows,
  (SELECT sum(requests) FROM intent_metrics) AS intent_requests,
  (SELECT count(*) FROM sessions WHERE impressions = 0) AS zero_exposure_requests,
  (SELECT count(*) FROM sessions WHERE clicks > impressions) AS clicks_exceeding_exposures,
  (SELECT count(*) FROM sessions WHERE purchases > clicks) AS purchases_exceeding_clicks;
